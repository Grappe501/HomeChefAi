#!/usr/bin/env node
/**
 * Sync marketing stats from live corpus manifests.
 * Run: npm run build:marketing-stats (also in npm run build)
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'fs';
import { join, resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const AI = join(ROOT, 'data', 'ai');

function countJson(dir) {
  if (!existsSync(dir)) return 0;
  return readdirSync(dir).filter((f) => f.endsWith('.json')).length;
}

function roundDownThousands(n) {
  return `${Math.floor(n / 1000).toLocaleString('en-US')},000+`;
}

function compactK(n) {
  return `${Math.floor(n / 1000)}K+`;
}

const dishManifest = JSON.parse(readFileSync(join(AI, 'dish-manifest.json'), 'utf8'));
const recipeTotal = Number(dishManifest.total ?? 0);
const cuisines = Object.keys(dishManifest.by_cuisine ?? {}).length;
const courses = Object.keys(dishManifest.by_course ?? {}).length;
const techniques = countJson(join(AI, 'techniques'));
const deepDives = countJson(join(AI, 'deep'));
const flavorProfiles = countJson(join(AI, 'flavor_profiles'));
const foodSources = countJson(join(AI, 'food_sources'));

const out = `/** AUTO-GENERATED by scripts/build-marketing-stats.mjs — do not edit manually */
export const CORPUS_STATS = {
  generatedAt: '${dishManifest.generated_at ?? new Date().toISOString()}',
  recipeTotal: ${recipeTotal},
  recipeCountFormatted: '${roundDownThousands(recipeTotal)}',
  recipeCountCompact: '${compactK(recipeTotal)}',
  recipeCountExact: '${recipeTotal.toLocaleString('en-US')}',
  cuisines: ${cuisines},
  courses: ${courses},
  techniques: ${techniques},
  deepDives: ${deepDives},
  flavorProfiles: ${flavorProfiles},
  foodSources: ${foodSources},
} as const;
`;

writeFileSync(join(ROOT, 'src/content/siteStats.generated.ts'), out, 'utf8');
console.log(
  `Marketing stats → ${recipeTotal.toLocaleString()} recipes · ${cuisines} cuisines · ${techniques} techniques · ${deepDives} deep dives`,
);
